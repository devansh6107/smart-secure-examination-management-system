-- ── Seats for each room ──
-- Generate 70 seats (7 rows x 10 columns) for every room with capacity 70
INSERT INTO Seat (room_id, seat_number, row_no, column_no)
SELECT r.room_id, CONCAT('R', row_t.r, 'C', col_t.c), row_t.r, col_t.c
FROM ExamRoom r
CROSS JOIN (SELECT 1 AS r UNION SELECT 2 UNION SELECT 3 UNION SELECT 4 UNION SELECT 5 UNION SELECT 6 UNION SELECT 7) row_t
CROSS JOIN (SELECT 1 AS c UNION SELECT 2 UNION SELECT 3 UNION SELECT 4 UNION SELECT 5
            UNION SELECT 6 UNION SELECT 7 UNION SELECT 8 UNION SELECT 9 UNION SELECT 10) col_t
WHERE r.capacity = 70;

